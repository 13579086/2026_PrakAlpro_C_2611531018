# Buat program untuk perulangan for dalam Python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_1018
# Program ini menggunakan fungsi input()

ulang_1018 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_1018 - 1)
for i_1018 in range(ulang_1018):
    print(i_1018, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_1018)
for i_1018 in range(1, ulang_1018 + 1):
    print(i_1018, end=" ")